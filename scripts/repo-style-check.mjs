#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';

import {
  extractCommandTypesWithOptionalFields,
  findUnknownUsages,
  scanDiscouragedServiceNames,
  scanFunctionInputContracts,
  scanOutputContractNaming,
  scanPlainObjectTypeAliases,
} from './repo-style-check/contract-rules.mjs';
import {
  estimateCyclomaticComplexity,
  extractRouteHandlerRanges,
  scanFactoryDefaults,
  scanFactorySpacing,
} from './repo-style-check/factory-route-rules.mjs';
import {
  extractCreateFactories,
  extractFunctionSignatures,
} from './repo-style-check/function-analysis.mjs';
import {
  isLayoutTypeScriptFile,
  layoutRuleIds,
  scanRepositoryLayout,
} from './repo-style-check/layout-rules.mjs';
import { lineFromOffset, lineOffsets } from './repo-style-check/source-text.mjs';

const args = new Set(process.argv.slice(2));
const outputContractMode = args.has('--output-contracts');
const objectInterfaceMode = args.has('--object-interfaces');
const layoutOnlyMode = args.has('--layout-only');
const layoutDetailsMode = args.has('--layout-details');
const maxDisplayedFindingCount = 200;
const explicitRoots = readExplicitRoots(process.argv);
const defaultMode = explicitRoots.length === 0;
const requestedRoots = defaultMode
  ? [path.resolve(process.cwd(), 'apps'), path.resolve(process.cwd(), 'packages')]
  : explicitRoots;

const checkedExtensions = new Set(['.ts', '.tsx', '.d.ts', '.mts', '.cts', '.mjs']);
const skippedDirectoryNames = new Set([
  '.git',
  '.deno',
  '.next',
  '.turbo',
  '.parcel-cache',
  'node_modules',
  'dist',
  'build',
  'coverage',
  'tmp',
  'tmp-media',
  '.nx',
  '.cache',
  '.husky',
  '.vscode',
  '.github',
  '.idea',
  'out',
]);
const nonProductionPathParts = new Set([
  'test',
  'tests',
  '__tests__',
  'mock',
  'mocks',
  '__mocks__',
  'fixture',
  '__fixtures__',
  'fixtures',
  'stories',
  'generated',
  'generated-types',
  'generated_types',
  'autogen',
  '.generated',
  '__generated__',
]);
const generatedPathPartPattern = new RegExp(
  '(^|[-_.])generated([-_.]|$)|^auto-generated$|^autogenerated$|' +
    '^codegen$|^\\.codegen$|^generated-code$',
  'u',
);
const testRunnerConfigPattern =
  /^(?:playwright|vitest|jest|cypress)(?:[.-][a-z0-9_-]+)*\.config\.[cm]?[jt]sx?$/u;
const limits = {
  fileLineCount: 400,
  lineWidth: 100,
  handlerLineCount: 30,
  handlerComplexity: 8,
  factoryBlockLineCount: 45,
  factoryDefaultFieldMinimum: 2,
  factoryOptionalFieldMinimum: 3,
  functionArgumentCount: 3,
};
const defaultLayoutRuleIds = [
  layoutRuleIds.directoryDensity,
  layoutRuleIds.featurePrefixCluster,
  layoutRuleIds.filenameStyle,
  layoutRuleIds.genericFilename,
  layoutRuleIds.genericRouteInit,
  layoutRuleIds.unapprovedMod,
];
const detailedLayoutRuleIds = [
  layoutRuleIds.primaryExportName,
  layoutRuleIds.browserRoomBoundary,
  layoutRuleIds.serverGroupStateVocabulary,
];

async function main() {
  if (args.has('--strict')) {
    console.error(
      'repo-style-check failed: strict mode is not available until warning debt is reviewed.',
    );
    process.exitCode = 1;
    return;
  }

  const scanRoots = await resolveRoots(requestedRoots);
  if (scanRoots.length === 0) {
    console.error('repo-style-check failed: no valid scan roots found.');
    process.exitCode = 1;
    return;
  }

  if (defaultMode) {
    console.warn(
      'repo-style-check: INFO - default run is intentionally narrowed to apps/ + packages/.',
    );
    console.warn(
      'repo-style-check: INFO - use --root . when reviewing production support code too.',
    );
  }

  const nestedFiles = await Promise.all(scanRoots.map(collectSourceFiles));
  const productionFiles = nestedFiles.flat().filter(isProductionCodeFile).sort();
  const productionSources = await Promise.all(
    productionFiles.map(async (file) => ({
      file,
      raw: await fs.readFile(file, 'utf8'),
    })),
  );
  const layoutSources = productionSources.filter(({ file }) => isLayoutTypeScriptFile(file));
  const layoutResult = scanRepositoryLayout({
    repoRoot: path.resolve(process.cwd()),
    sources: layoutSources,
    includeDetails: layoutDetailsMode,
  });
  const findings = [];

  if (!layoutOnlyMode) {
    for (const source of productionSources) {
      const messages = scanFile(source.raw);
      findings.push(
        ...messages.map((message) => ({
          file: source.file,
          kind: 'warn',
          message,
        })),
      );
    }
  }
  findings.push(...layoutResult.findings);

  printFindings({
    findings,
    scanRoots,
    layoutCounts: layoutResult.counts,
    activeLayoutRuleIds: [
      ...defaultLayoutRuleIds,
      ...(layoutDetailsMode ? detailedLayoutRuleIds : []),
    ].toSorted(),
  });
  process.exitCode = 0;
}

function scanFile(raw) {
  const messages = [];
  const lines = raw.split('\n');
  const offsets = lineOffsets(raw);

  if (lines.length > limits.fileLineCount) {
    messages.push(
      `File length ${lines.length} > ${limits.fileLineCount}; prefer a cohesive ` +
        'domain split. Route modules normally split by read/write/admin responsibility.',
    );
  }

  const longLines = lines
    .map((text, index) => ({ line: index + 1, text }))
    .filter((line) => line.text.length > limits.lineWidth);
  for (const line of longLines.slice(0, 8)) {
    messages.push(
      `Line ${line.line} exceeds ${limits.lineWidth} chars ` +
        `(actual ${line.text.length}). Prefer wrapped, traceable formatting.`,
    );
  }
  if (longLines.length > 8) {
    messages.push(`... and ${longLines.length - 8} additional over-long lines.`);
  }

  for (const range of extractRouteHandlerRanges(raw)) {
    const startLine = lineFromOffset(offsets, range.start);
    const endLine = lineFromOffset(offsets, range.end);
    const handlerLineCount = endLine - startLine + 1;
    const handlerText = raw.slice(range.start, range.end);

    if (handlerLineCount > limits.handlerLineCount) {
      messages.push(
        `Route handler starting line ${startLine} has ${handlerLineCount} lines ` +
          `(target <= ${limits.handlerLineCount}).`,
      );
    }

    const complexity = estimateCyclomaticComplexity(handlerText);
    if (complexity > limits.handlerComplexity) {
      messages.push(
        `Route handler starting line ${startLine} has estimated complexity ` +
          `${complexity} (target <= ${limits.handlerComplexity}).`,
      );
    }
  }

  for (const commandType of extractCommandTypesWithOptionalFields(lines)) {
    const fields = commandType.fields.map((field) => field.text).join('; ');
    messages.push(
      `Command model ${commandType.name} contains optional fields, e.g. ${fields}. ` +
        'Keep request optionality in a separate request type and decode to required fields.',
    );
  }

  const functions = extractFunctionSignatures(raw);
  messages.push(
    ...scanFunctionInputContracts(functions, limits.functionArgumentCount),
    ...scanDiscouragedServiceNames(raw),
  );
  if (outputContractMode) {
    messages.push(...scanOutputContractNaming(raw, functions));
  }
  if (objectInterfaceMode) {
    messages.push(...scanPlainObjectTypeAliases(raw));
  }

  for (const factory of extractCreateFactories(raw)) {
    messages.push(
      ...scanFactorySpacing(raw, factory, limits.factoryBlockLineCount),
      ...scanFactoryDefaults({
        raw,
        lines,
        factory,
        limits: {
          defaultFieldMinimum: limits.factoryDefaultFieldMinimum,
          optionalFieldMinimum: limits.factoryOptionalFieldMinimum,
        },
      }),
    );
  }

  const unknownUsages = findUnknownUsages(lines);
  for (const usage of unknownUsages.slice(0, 5)) {
    messages.push(
      `Review unknown at line ${usage.line}: ${usage.text} ` +
        'Keep it at an untrusted boundary and normalize it before domain logic.',
    );
  }
  if (unknownUsages.length > 5) {
    messages.push(
      `... and ${unknownUsages.length - 5} additional unknown occurrences. ` +
        'Reduce unknown propagation at domain boundaries.',
    );
  }

  return messages;
}

function readExplicitRoots(argv) {
  const roots = [];
  for (let index = 0; index < argv.length - 1; index += 1) {
    if (argv[index] === '--root') {
      roots.push(path.resolve(argv[index + 1]));
    }
  }
  return roots;
}

async function resolveRoots(candidates) {
  const existingRoots = [];
  for (const candidate of candidates) {
    try {
      const stat = await fs.stat(candidate);
      if (stat.isDirectory()) {
        existingRoots.push(candidate);
      }
    } catch {
      // Missing optional roots are ignored so the checker supports partial checkouts.
    }
  }
  return existingRoots;
}

async function collectSourceFiles(current) {
  const files = [];
  const entries = await fs.readdir(current, { withFileTypes: true });

  for (const entry of entries) {
    const next = path.join(current, entry.name);
    if (entry.isDirectory()) {
      if (skippedDirectoryNames.has(entry.name) || entry.name.startsWith('.')) {
        continue;
      }
      files.push(...(await collectSourceFiles(next)));
      continue;
    }

    if (entry.isFile() && checkedExtensions.has(path.extname(entry.name).toLowerCase())) {
      files.push(next);
    }
  }

  return files;
}

function isProductionCodeFile(file) {
  const normalized = file.replace(/\\/gu, '/').toLowerCase();
  const parts = normalized.split('/');
  if (
    parts.some(
      (part) => part && (nonProductionPathParts.has(part) || generatedPathPartPattern.test(part)),
    )
  ) {
    return false;
  }

  const base = parts[parts.length - 1];
  if (testRunnerConfigPattern.test(base)) {
    return false;
  }

  if (
    /\.generated(?:\.d)?\.[cm]?(?:t|j)sx?$/u.test(base) ||
    /\.gen(?:\.d)?\.[cm]?(?:t|j)sx?$/u.test(base) ||
    /\.pb(?:\.d)?\.[cm]?(?:t|j)sx?$/u.test(base)
  ) {
    return false;
  }

  return !/[\w-]+\.(?:test|spec|mock|fixture|stories)\.(?:d\.[cm]?ts|[cm]ts|tsx|jsx|js)$/u.test(
    base,
  );
}

function printFindings(input) {
  if (input.findings.length === 0) {
    console.log('repo-style-check: PASS (no issues found in this run)');
  } else {
    console.log('repo-style-check: WARN');
    for (const finding of input.findings.slice(0, maxDisplayedFindingCount)) {
      const rulePrefix = finding.ruleId === undefined ? '' : `[${finding.ruleId}] `;
      console.log(`${finding.kind.toUpperCase()}: ${finding.file}`);
      console.log(`  - ${rulePrefix}${finding.message}`);
    }
    if (input.findings.length > maxDisplayedFindingCount) {
      console.log(
        `\n${input.findings.length - maxDisplayedFindingCount} additional findings ` +
          'not displayed. ' +
          'Use --root with a narrower path for a reviewable result.',
      );
    }
    console.log(
      `\nSummary: ${input.findings.length} non-blocking issues found in ` +
        `${input.scanRoots.join(', ')}.`,
    );
  }

  console.log(
    'Layout summary: ' +
      input.activeLayoutRuleIds
        .map((ruleId) => `${ruleId}=${input.layoutCounts[ruleId]}`)
        .join(', '),
  );
}

main().catch((error) => {
  console.error('repo-style-check failed:', error);
  process.exitCode = 1;
});
