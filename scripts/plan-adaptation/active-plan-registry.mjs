import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { parseAdaptivePlanRecord } from './adaptive-plan-record.mjs';

const columns = ['Plan', 'Capability owner', 'Status', 'Checkpoint decision', 'Next slice'];

export function readActivePlans(repoRoot) {
  const plansRoot = path.join(repoRoot, 'plans');
  return readdirSync(plansRoot, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md') && entry.name !== 'README.md')
    .flatMap((entry) => {
      const relativePath = `plans/${entry.name}`;
      const markdown = readFileSync(path.join(repoRoot, relativePath), 'utf8');
      if (!markdown.includes('```plan-adaptation-v1')) {
        return [];
      }
      return [{ planPath: relativePath, record: parseAdaptivePlanRecord(markdown, relativePath) }];
    })
    .filter(({ record }) => record.status === 'active')
    .sort((left, right) => left.record.planId.localeCompare(right.record.planId));
}

export function toActivePlanRegistry(activePlans) {
  const rows = activePlans.map(({ record }) => [
    cell(record.planId),
    cell(record.capabilities.map((capability) => capability.owner).join(', ')),
    cell(record.status),
    cell(record.checkpoint.decision),
    cell(record.checkpoint.nextSlices.join(', ')),
  ]);
  const widths = columns.map((column, index) => {
    return Math.max(column.length, 3, ...rows.map((row) => row[index].length));
  });
  const lines = [
    '# Active adaptive plans',
    '',
    'This file is generated by `npm run plan:adapt`. Do not edit it manually.',
    '',
    tableRow(columns, widths),
    tableRow(
      widths.map((width) => '-'.repeat(width)),
      widths,
    ),
    ...rows.map((row) => tableRow(row, widths)),
    '',
  ];
  return lines.join('\n');
}

function tableRow(values, widths) {
  return `| ${values.map((value, index) => value.padEnd(widths[index])).join(' | ')} |`;
}

function cell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

export function writeActivePlanRegistry(repoRoot) {
  writeFileSync(
    path.join(repoRoot, 'plans/README.md'),
    toActivePlanRegistry(readActivePlans(repoRoot)),
  );
}
